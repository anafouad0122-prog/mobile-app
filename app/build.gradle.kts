android {
    namespace = "com.fouad.cuttingnotebook"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.fouad.cuttingnotebook"
        minSdk = 24
        targetSdk = 35
        versionCode = 1
        versionName = "1.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        resourceConfigurations += listOf("ar")
    }

    // Signing details come from keystore.properties at the repo root, which is git-ignored.
    // See README section 5. Without that file a release build is produced unsigned, so a
    // missing keystore fails loudly at install time rather than silently shipping a build
    // signed with a different key (which would refuse to update an installed app).
    val keystoreProperties = rootProject.file("keystore.properties").takeIf { it.exists() }
        ?.let { file ->
            Properties().apply { file.inputStream().use { stream -> load(stream) } }
        }

    signingConfigs {
        if (keystoreProperties != null) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
                // v1 JAR signing is only needed below Android 7, which minSdk rules out.
                enableV2Signing = true
                enableV3Signing = true
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (keystoreProperties != null) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
        isCoreLibraryDesugaringEnabled = true
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    testOptions {
        unitTests.isIncludeAndroidResources = true
        unitTests.all {
            // Robolectric fetches its android-all jar at runtime; Maven Central rate-limits
            // some networks, so it reads from the same mirror the build uses.
            it.systemProperty(
                "robolectric.dependency.repo.url",
                "https://maven-central.storage-download.googleapis.com/maven2/",
            )
            it.systemProperty("robolectric.logging.enabled", "false")
        }
    }

    packaging {
        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }
}

